import react from '@vitejs/plugin-react-swc';
import { createHash } from 'crypto';
import { copyFileSync, existsSync, readFileSync, writeFileSync } from 'fs';
import { basename, resolve as pathResolve, relative } from 'path';
import postcssPresetEnv from 'postcss-preset-env';
import { type Plugin, defineConfig, loadEnv } from 'vite';
import svgr from 'vite-plugin-svgr';

import pkg from '../../../package.json';
import paths from './paths';

/** Favicon rasterization has no CSS context; currentColor in logo.svg renders black. */
const faviconLogoSvgPath = pathResolve(paths.assets, 'logo-favicon.svg');
const themeStyl = pathResolve(paths.src, 'theme.styl');

/** GitHub Pages project sites live at /<repo>/; set PUBLIC_PATH=/repo-name/ for production deploy. */
function normalizePublicPath(raw: string | undefined) {
  const v = (raw && String(raw).trim()) || '/';
  if (v === '/') {
    return '/';
  }
  const withLeading = v.startsWith('/') ? v : `/${v}`;
  return withLeading.endsWith('/') ? withLeading : `${withLeading}/`;
}

function routerBasenameFromPublicPath(publicPath: string) {
  if (publicPath === '/') {
    return '';
  }
  return publicPath.replace(/\/$/, '');
}

const STYL_MODULE_QUERY = '?.module.styl';

/**
 * Every `.styl` file is a CSS module (no `.module.styl` suffix), but Vite only
 * treats `*.module.*` ids as modules. Tag resolved `.styl` imports with a query
 * ending in `.module.styl` so Vite's CSS-modules check matches while the id
 * still points at the real file (HMR and file reads use the path before `?`).
 */
function stylusModules(): Plugin {
  return {
    name: 'uilib:stylus-modules',
    enforce: 'pre',
    async resolveId(source, importer, options) {
      if (!importer || !/\.styl$/.test(source)) return null;
      const resolved = await this.resolve(source, importer, {
        ...options,
        skipSelf: true,
      });
      if (!resolved || resolved.external || resolved.id.includes('?')) {
        return resolved;
      }
      return { ...resolved, id: `${resolved.id}${STYL_MODULE_QUERY}` };
    },
  };
}

/** `import text from './AGENT.md'` → file contents as a string (webpack `asset/source`). */
function rawMarkdown(): Plugin {
  return {
    name: 'uilib:raw-md',
    enforce: 'pre',
    load(id) {
      if (!id.endsWith('.md')) return null;
      return `export default ${JSON.stringify(readFileSync(id, 'utf8'))};`;
    },
  };
}

/** `[name]__[local]___[hash:base64:5]`, as css-loader produced it under webpack. */
function scopedName(local: string, filename: string) {
  const file = filename.split('?')[0];
  const name = basename(file).replace(/\.[^.]+$/, '');
  const hash = createHash('md5')
    .update(`${relative(paths.src, file)}\0${local}`)
    .digest('base64url')
    .slice(0, 5);
  return `${name}__${local}___${hash}`;
}

/**
 * Keep `Foo.styl.d.ts` class typings in sync (what css-modules-typescript-loader
 * did under webpack). Rewrites only when the set of class names changed, so
 * files formatted by prettier are left alone.
 */
function writeStylTypings(cssFileName: string, json: Record<string, string>) {
  const dts = `${cssFileName.split('?')[0]}.d.ts`;
  const keys = Object.keys(json).sort();
  const existing = existsSync(dts)
    ? [...readFileSync(dts, 'utf8').matchAll(/^\s+'?([^':\s]+)'?: string;$/gm)]
        .map(m => m[1])
        .sort()
    : null;
  if (existing && existing.join('\n') === keys.join('\n')) return;
  writeFileSync(
    dts,
    [
      '// This file is automatically generated.',
      '// Please do not change this file!',
      'interface CssExports {',
      ...keys.map(k => `  '${k}': string;`),
      '}',
      'export const cssExports: CssExports;',
      'export default cssExports;',
      '',
    ].join('\n'),
  );
}

/** Build only: rasterize favicons + web manifest and inject their tags. */
function favicons(base: string): Plugin {
  const prefix = 'favicons/';
  let response: {
    images: { name: string; contents: Buffer }[];
    files: { name: string; contents: string }[];
    html: string[];
  } | null = null;

  return {
    name: 'uilib:favicons',
    apply: 'build',
    async buildStart() {
      if (!existsSync(faviconLogoSvgPath)) return;
      const { favicons: generate } = await import('favicons');
      response = await generate(faviconLogoSvgPath, {
        path: `${base}${prefix}`,
        appName: 'Sybilion Design System',
        developerName: 'Sybilion',
        developerURL: null,
        background: '#fff',
        theme_color: '#1a1a1a',
        display: 'standalone',
        icons: {
          android: true,
          appleIcon: true,
          appleStartup: false,
          favicons: true,
          windows: true,
          yandex: false,
        },
      });
    },
    generateBundle() {
      if (!response) return;
      for (const { name, contents } of [
        ...response.images,
        ...response.files,
      ]) {
        this.emitFile({
          type: 'asset',
          fileName: `${prefix}${name}`,
          source: contents,
        });
      }
    },
    transformIndexHtml(html) {
      if (!response) return html;
      return html.replace('</head>', `${response.html.join('')}</head>`);
    },
  };
}

/** GitHub Pages serves 404.html for missing paths; same shell as index.html so SPA routes work. */
function spaFallback404(): Plugin {
  let outDir = '';
  return {
    name: 'uilib:spa-404',
    apply: 'build',
    configResolved(config) {
      outDir = config.build.outDir;
    },
    closeBundle() {
      copyFileSync(
        pathResolve(outDir, 'index.html'),
        pathResolve(outDir, '404.html'),
      );
    },
  };
}

export default defineConfig(({ mode }) => {
  const isDev = mode === 'development';
  const env = loadEnv(mode, process.cwd(), '');
  const publicPath = normalizePublicPath(env.PUBLIC_PATH);

  const alias: Record<string, string> = {
    '#uilib': paths.src,
    uilib: paths.src,
    'docs/components': `${paths.docs}/components`,
  };
  if (existsSync(themeStyl)) {
    alias.theme = themeStyl;
  }

  return {
    base: publicPath,
    publicDir: paths.assets,

    resolve: { alias },

    define: {
      isDEV: JSON.stringify(isDev),
      VERSION: JSON.stringify(pkg.version),
      DOCS_ROUTER_BASENAME: JSON.stringify(
        routerBasenameFromPublicPath(publicPath),
      ),
    },

    css: {
      modules: {
        generateScopedName: scopedName,
        getJSON: isDev ? writeStylTypings : undefined,
      },
      preprocessorOptions: {
        // `@import 'lib/theme.styl'` resolves against src/ (webpack resolve.modules).
        // Vite looks options up by file extension, so `.styl` reads `styl`.
        styl: { paths: [paths.src, paths.docs] },
      },
      postcss: {
        // Autoprefixer is on by default in postcss-preset-env.
        plugins: [postcssPresetEnv({ stage: 3 })],
      },
    },

    plugins: [
      stylusModules(),
      rawMarkdown(),
      svgr({
        include: '**/*.svg',
        // Rendered as <img>/background: keep the default URL import.
        exclude: '**/components/ui/WorldMap/map.svg',
        svgrOptions: { icon: true },
      }),
      react(),
      favicons(publicPath),
      spaFallback404(),
    ],

    server: {
      port: Number(env.PORT) || 8181,
    },

    build: {
      outDir: paths.build,
      emptyOutDir: true,
      sourcemap: false,
    },
  };
});
