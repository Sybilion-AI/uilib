#!/usr/bin/env node
/**
 * Build concatenated AGENT.md glossaries for coding agents.
 *
 * Usage:
 *   node scripts/build-agent-glossary.mjs content
 *   node scripts/build-agent-glossary.mjs workspace
 *   node scripts/build-agent-glossary.mjs --all
 *
 * Env:
 *   SYBILION_UILIB_SRC — override uilib src root
 *   AGENT_GLOSSARY_APPEND — comma-separated extra markdown files (e.g. app report-only tiles)
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

import { PROFILES } from './agent-glossary-profiles.mjs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const uilibRoot = path.resolve(__dirname, '..');

function resolveSrcRoot() {
  if (process.env.SYBILION_UILIB_SRC) {
    return path.resolve(process.env.SYBILION_UILIB_SRC);
  }
  return path.join(uilibRoot, 'src');
}

function readSection(filePath, { required }) {
  if (!fs.existsSync(filePath)) {
    if (required) {
      throw new Error(`Missing AGENT doc: ${filePath}`);
    }
    console.warn(`skip (missing): ${filePath}`);
    return null;
  }
  return fs.readFileSync(filePath, 'utf8').trim();
}

function buildGlossary(profileKey) {
  const profile = PROFILES[profileKey];
  if (!profile) {
    throw new Error(
      `Unknown profile "${profileKey}". Use: ${Object.keys(PROFILES).join(', ')}`,
    );
  }
  const srcRoot = resolveSrcRoot();
  const sections = [profile.title, ''];

  for (const rel of profile.paths) {
    const body = readSection(path.join(srcRoot, rel), { required: false });
    if (body) sections.push('', body);
  }

  const appendEnv = process.env.AGENT_GLOSSARY_APPEND ?? '';
  for (const raw of appendEnv
    .split(',')
    .map(s => s.trim())
    .filter(Boolean)) {
    const resolved = path.isAbsolute(raw) ? raw : path.resolve(uilibRoot, raw);
    const body = readSection(resolved, { required: true });
    if (body) sections.push('', body);
  }

  return sections.join('\n');
}

function writeOutputs(profileKey, glossary) {
  const outDir = path.join(uilibRoot, 'dist/agent-glossary');
  fs.mkdirSync(outDir, { recursive: true });
  const mdPath = path.join(outDir, `${profileKey}.md`);
  fs.writeFileSync(mdPath, `${glossary}\n`, 'utf8');

  const escaped = glossary
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$\{/g, '\\${');
  const constName =
    profileKey === 'content'
      ? 'CONTENT_AGENT_UI_GLOSSARY'
      : 'WORKSPACE_AGENT_UI_GLOSSARY';
  const tsPath = path.join(outDir, `${profileKey}.generated.ts`);
  const ts = `/** Generated by scripts/build-agent-glossary.mjs — do not edit. */\nexport const ${constName} = \`${escaped}\`;\n`;
  fs.writeFileSync(tsPath, ts, 'utf8');
  console.log(`Wrote ${mdPath} (${glossary.length} chars)`);
  console.log(`Wrote ${tsPath}`);
}

const arg = process.argv[2] ?? 'content';
if (arg === '--all') {
  for (const key of Object.keys(PROFILES)) {
    writeOutputs(key, buildGlossary(key));
  }
} else {
  writeOutputs(arg, buildGlossary(arg));
}
